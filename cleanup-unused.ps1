$found = @(); $bytes = 0
foreach ($rel in $items) {
  $p = Join-Path $root $rel
  if (Test-Path -LiteralPath $p) {
    $found += $rel
    $item = Get-Item -LiteralPath $p -Force
    if ($item.PSIsContainer) { $bytes += (Get-ChildItem -LiteralPath $p -Recurse -File -Force | Measure-Object Length -Sum).Sum }
    else { $bytes += $item.Length }
  }
}
Write-Host ""
Write-Host ("Found {0} of {1} items to move ({2:N0} MB)." -f $found.Count, $items.Count, ($bytes / 1MB))
Write-Host "They will be MOVED (not deleted) to: $dest"
Write-Host ""
$answer = Read-Host "Type Y to move them"
if ($answer -ne 'Y' -and $answer -ne 'y') { Write-Host "Nothing moved."; exit 0 }
$moved = 0; $failed = @()
foreach ($rel in $found) {
  $src = Join-Path $root $rel
  $target = Join-Path $dest $rel
  try {
    New-Item -ItemType Directory -Force -Path (Split-Path $target -Parent) | Out-Null
    Move-Item -LiteralPath $src -Destination $target -Force
    $moved++
  } catch { $failed += "$rel  ($($_.Exception.Message))" }
}
$found | Set-Content -Encoding UTF8 (Join-Path $dest 'moved-files.txt')
# Remove folders that are now empty (e.g. assets\report-builder\zoomed-screenshots).
Get-ChildItem -LiteralPath (Join-Path $root 'assets'), (Join-Path $root 'drafts') -Recurse -Directory -Force |
  Sort-Object { $_.FullName.Length } -Descending |
  Where-Object { -not (Get-ChildItem -LiteralPath $_.FullName -Force) } |
  ForEach-Object { Remove-Item -LiteralPath $_.FullName }
Write-Host ""
Write-Host "Moved $moved items. A list is in moved-files.txt in that folder."
if ($failed.Count) { Write-Host "Could not move:"; $failed | ForEach-Object { Write-Host "  $_" } }
Write-Host "To undo, move the folders back from $dest."
