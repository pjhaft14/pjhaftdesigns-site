const { chromium } = require('C:/Users/pjhaf/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
  assert(await page.locator('.track-image').evaluate(image => image.complete && image.naturalWidth === 529));
  await page.waitForTimeout(3250);
  const before = await page.locator('#vehicle-1').getAttribute('transform');
  await page.waitForTimeout(350);
  assert.notEqual(await page.locator('#vehicle-1').getAttribute('transform'), before);
  await page.getByRole('button', { name: 'Pause vehicle simulation' }).click();
  const pausedPosition = await page.locator('#vehicle-1').getAttribute('transform');
  await page.waitForTimeout(150);
  assert.equal(await page.locator('#vehicle-1').getAttribute('transform'), pausedPosition);
  await page.locator('[data-track="B"]').click();
  assert(await page.locator('.pin-sensor').isVisible());
  assert(!await page.locator('.pin-brake').isVisible());
  await page.locator('[data-track="A"]').click();
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  assert.match(await page.locator('#map-art').getAttribute('style'), /1\.3/);
  await page.getByRole('button', { name: 'Reset map', exact: true }).click();
  await page.locator('.pin-brake').click();
  await page.screenshot({ path: path.join(__dirname, 'component-detail.png') });
  await page.getByRole('button', { name: 'Create work request', exact: true }).click();
  await page.locator('[name=description]').fill('Inspect brake <actuator> & confirm repair');
  await page.getByRole('button', { name: 'Submit work request', exact: true }).click();
  await page.getByRole('button', { name: 'Request a part', exact: true }).click();
  await page.locator('[name=quantity]').fill('2');
  await page.screenshot({ path: path.join(__dirname, 'parts-request.png') });
  await page.getByRole('button', { name: 'Submit parts request', exact: true }).click();
  await page.getByRole('button', { name: 'View linked requests', exact: true }).click();
  assert.match(await page.locator('#requests-content').innerText(), /Availability pending/);
  assert.match(await page.locator('#requests-content').innerText(), /2 × Brake actuator assembly/);
  assert.match(await page.locator('#requests-content').innerText(), /Inspect brake <actuator> & confirm repair/);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.locator('.pin-lift').click();
  await page.getByRole('button', { name: 'Escalate now', exact: true }).click();
  assert.equal(await page.locator('[name=window]').inputValue(), 'Immediate engineering review');
  await page.getByRole('button', { name: 'Submit work request', exact: true }).click();
  await page.getByRole('button', { name: 'View request', exact: true }).click();
  assert.equal(await page.locator('.request-item').count(), 2);
  assert.match(await page.locator('.request-item').first().innerText(), /Escalated/);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
    await page.screenshot({ path: path.join(__dirname, width === 1440 ? 'desktop.png' : `viewport-${width}.png`), fullPage: true });
  }
  await page.locator('.pin-brake').click();
  await page.getByRole('button', { name: 'View work request', exact: true }).click();
  assert(await page.locator('#requests-view').isVisible());
  const reduced = await browser.newPage({ reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
  await reduced.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
  assert(await reduced.getByRole('button', { name: 'Play vehicle simulation' }).isVisible());
  await reduced.locator('.pin-brake').click();
  await reduced.getByRole('button', { name: 'Create work request', exact: true }).click();
  await reduced.screenshot({ path: path.join(__dirname, 'mobile-work-request.png') });
  await reduced.getByRole('button', { name: 'Cancel', exact: true }).click();
  await reduced.keyboard.press('Escape');
  assert(!await reduced.locator('#event-drawer').isVisible());
  assert.deepEqual(errors, []);
  console.log('PASS: asset rendering; animation and pause; track selection; zoom; work + parts flow; escaped input; escalation; 5 viewport widths; reduced motion; cancel and Escape.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
