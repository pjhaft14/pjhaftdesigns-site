#!/usr/bin/env node
// Regenerates assets/icons.svg, the site's icon sprite, from the icons the pages actually use.
//
//   node scripts/icons.cjs
//
// To add an icon, either write `<i data-lucide="name"></i>` in a page (this script converts it
// to sprite markup) or call `window.siteIcon('name')` from a script; then run this script.
// Icon names and shapes come from Lucide (https://lucide.dev, ISC licence), vendored in
// scripts/vendor/lucide.min.js. That file is only read here and is never shipped.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const ctx = { window: {}, self: {} };
ctx.globalThis = ctx;
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname, 'vendor/lucide.min.js'), 'utf8'), ctx);
const icons = ctx.lucide.icons;
const DEFAULTS = icons.Menu[1];   // Lucide's standard <svg> attributes

const pascal = n => n.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const esc = v => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const attrs = o => Object.entries(o).map(([k, v]) => ` ${k}="${esc(v)}"`).join('');
const pages = fs.readdirSync(root).filter(f => f.endsWith('.html'));
const scripts = fs.readdirSync(root).filter(f => f.endsWith('.js'));
const legacyTag = /<i\b([^>]*?)\bdata-lucide="([\w-]+)"([^>]*)>\s*<\/i>/g;

// 1. Convert any <i data-lucide> placeholders into sprite markup (Lucide's own output shape).
for (const f of pages) {
  const p = path.join(root, f);
  const before = fs.readFileSync(p, 'utf8');
  const after = before.replace(legacyTag, (m, pre, name, post) => {
    const own = {};
    for (const a of (pre + ' ' + post).matchAll(/([\w:-]+)(?:="([^"]*)")?/g)) own[a[1]] = a[2] ?? '';
    const cls = ['lucide', `lucide-${name}`, own.class].filter(Boolean).join(' ');
    delete own.class;
    return `<svg${attrs({ ...DEFAULTS, 'data-lucide': name, ...own, class: cls })}><use href="assets/icons.svg#${name}"></use></svg>`;
  });
  if (after !== before) { fs.writeFileSync(p, after); console.log(`converted icon placeholders in ${f}`); }
}

// 2. Collect every icon referenced by pages and scripts.
const used = new Set();
for (const f of pages) for (const m of fs.readFileSync(path.join(root, f), 'utf8').matchAll(/icons\.svg#([\w-]+)/g)) used.add(m[1]);
for (const f of scripts) for (const m of fs.readFileSync(path.join(root, f), 'utf8').matchAll(/siteIcon\((?:[^)]*?)['"]([\w-]+)['"]/g)) used.add(m[1]);
// siteIcon(cond ? 'a' : 'b') passes two names; pick up both.
for (const f of scripts) for (const m of fs.readFileSync(path.join(root, f), 'utf8').matchAll(/siteIcon\(([^)]*)\)/g)) for (const n of m[1].matchAll(/['"]([\w-]+)['"]/g)) if (icons[pascal(n[1])]) used.add(n[1]);

// 3. Write the sprite. Presentation attributes stay on each referencing <svg> and inherit.
const symbols = [...used].sort().map(name => {
  const node = icons[pascal(name)];
  if (!node) throw new Error(`Unknown Lucide icon "${name}"`);
  return `<symbol id="${name}" viewBox="0 0 24 24">${node[2].map(([t, a]) => `<${t}${attrs(a)}/>`).join('')}</symbol>`;
});
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons (https://lucide.dev, ISC licence). Generated by scripts/icons.cjs; do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
fs.writeFileSync(path.join(root, 'assets/icons.svg'), sprite);
console.log(`assets/icons.svg: ${used.size} icons, ${(sprite.length / 1024).toFixed(1)} KB`);
